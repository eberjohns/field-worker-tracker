"""Automated System Versioning Tool for Field Worker Tracker (FWT).

Enforces semantic versioning (v<MAJOR>.<MINOR>.<PATCH>):
- MAJOR (leftmost): Incremented intentionally by developer (CLI or direct file update).
- MINOR (center): Increments on commits to a new branch (resets patch to 0).
- PATCH (rightmost): Increments for each commit on the current branch (including direct commits on main).

Synchronizes:
- version.json (Root single source of truth)
- web/src/version.ts (Frontend compile-time constant)
- web/package.json
- backend/pyproject.toml
- docs/system-versioning.md (History log)
"""

import argparse
from datetime import UTC, datetime
import json
import os
import re
import subprocess
import sys

ROOT_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
VERSION_JSON = os.path.join(ROOT_DIR, "version.json")
WEB_VERSION_TS = os.path.join(ROOT_DIR, "web", "src", "version.ts")
WEB_PACKAGE_JSON = os.path.join(ROOT_DIR, "web", "package.json")
BACKEND_PYPROJECT = os.path.join(ROOT_DIR, "backend", "pyproject.toml")
DOCS_VERSIONING_MD = os.path.join(ROOT_DIR, "docs", "system-versioning.md")


def get_git_info() -> tuple[str, str]:
    """Retrieve current branch and short commit hash from git."""
    try:
        branch_res = subprocess.run(
            ["git", "rev-parse", "--abbrev-ref", "HEAD"],
            capture_output=True,
            text=True,
            cwd=ROOT_DIR,
        )
        branch = branch_res.stdout.strip() if branch_res.returncode == 0 else "main"

        commit_res = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
            cwd=ROOT_DIR,
        )
        commit = commit_res.stdout.strip() if commit_res.returncode == 0 else "unknown"
        return branch, commit
    except Exception:
        return "main", "unknown"


def load_version() -> dict:
    if os.path.exists(VERSION_JSON):
        with open(VERSION_JSON, "r", encoding="utf-8") as f:
            return json.load(f)
    return {
        "version": "1.0.0",
        "major": 1,
        "minor": 0,
        "patch": 0,
        "last_branch": "main",
        "last_commit": "",
        "updated_at": datetime.now(UTC).isoformat(),
    }


def save_version(v_data: dict):
    with open(VERSION_JSON, "w", encoding="utf-8") as f:
        json.dump(v_data, f, indent=2)
        f.write("\n")


def sync_all_targets(version_str: str, message: str = ""):
    today_str = datetime.now(UTC).strftime("%Y-%m-%d")

    # 1. web/src/version.ts
    os.makedirs(os.path.dirname(WEB_VERSION_TS), exist_ok=True)
    with open(WEB_VERSION_TS, "w", encoding="utf-8") as f:
        f.write(f'// Auto-generated by tools/version.py - Canonical Version Source\n')
        f.write(f'export const APP_VERSION = "{version_str}";\n')
        f.write(f'export const APP_BUILD_DATE = "{today_str}";\n')

    # 2. web/package.json
    if os.path.exists(WEB_PACKAGE_JSON):
        with open(WEB_PACKAGE_JSON, "r", encoding="utf-8") as f:
            pkg = json.load(f)
        pkg["version"] = version_str
        with open(WEB_PACKAGE_JSON, "w", encoding="utf-8") as f:
            json.dump(pkg, f, indent=2)
            f.write("\n")

    # 3. backend/pyproject.toml
    if os.path.exists(BACKEND_PYPROJECT):
        with open(BACKEND_PYPROJECT, "r", encoding="utf-8") as f:
            content = f.read()
        new_content = re.sub(
            r'version\s*=\s*"[^"]+"',
            f'version = "{version_str}"',
            content,
            count=1,
        )
        with open(BACKEND_PYPROJECT, "w", encoding="utf-8") as f:
            f.write(new_content)

    # 4. docs/system-versioning.md
    update_docs_changelog(version_str, message)


def update_docs_changelog(version_str: str, message: str):
    now_iso = datetime.now(UTC).isoformat()
    branch, commit = get_git_info()

    if not os.path.exists(DOCS_VERSIONING_MD):
        header = """# System Versioning & Release History

Field Worker Tracker follows semantic versioning `v<MAJOR>.<MINOR>.<PATCH>`:
- **MAJOR**: Incremented by the developer for architectural or breaking releases.
- **MINOR**: Incremented automatically when commits are made on a new branch.
- **PATCH**: Incremented automatically for each commit on the branch (or direct commits).

## Version History Log

| Version | Date (UTC) | Branch | Commit | Note |
|---|---|---|---|---|
"""
        with open(DOCS_VERSIONING_MD, "w", encoding="utf-8") as f:
            f.write(header)

    with open(DOCS_VERSIONING_MD, "r", encoding="utf-8") as f:
        lines = f.readlines()

    # Check if this version is already the most recent row
    row = f"| **v{version_str}** | {now_iso[:10]} | `{branch}` | `{commit}` | {message or 'Automated version update'} |\n"
    if lines and not any(f"| **v{version_str}** |" in line for line in lines):
        lines.append(row)
        with open(DOCS_VERSIONING_MD, "w", encoding="utf-8") as f:
            f.writelines(lines)


def bump(level: str, note: str = "") -> str:
    v = load_version()
    major = int(v.get("major", 1))
    minor = int(v.get("minor", 0))
    patch = int(v.get("patch", 0))

    if level == "major":
        major += 1
        minor = 0
        patch = 0
    elif level == "minor":
        minor += 1
        patch = 0
    elif level == "patch":
        patch += 1

    branch, commit = get_git_info()
    version_str = f"{major}.{minor}.{patch}"
    v["version"] = version_str
    v["major"] = major
    v["minor"] = minor
    v["patch"] = patch
    v["last_branch"] = branch
    v["last_commit"] = commit
    v["updated_at"] = datetime.now(UTC).isoformat()

    save_version(v)
    sync_all_targets(version_str, note or f"Bumped {level} to v{version_str}")
    print(f"Version bumped to v{version_str} ({level})")
    return version_str


def auto_increment(note: str = "") -> str:
    v = load_version()
    branch, commit = get_git_info()
    last_branch = v.get("last_branch", "")

    # If the commit is on a new branch (and last_branch was recorded and differs):
    # Increment MINOR and reset PATCH
    if branch and last_branch and branch != last_branch and not branch.startswith("HEAD"):
        print(f"New branch detected ('{last_branch}' -> '{branch}'). Incrementing MINOR version...")
        return bump("minor", note or f"New branch '{branch}'")
    else:
        # Same branch or direct commit on current branch/main:
        # Increment PATCH
        return bump("patch", note or f"Commit on '{branch}'")


def install_git_hook():
    hooks_dir = os.path.join(ROOT_DIR, ".git", "hooks")
    if not os.path.exists(hooks_dir):
        print(f"Error: .git/hooks directory not found at {hooks_dir}")
        return

    hook_path = os.path.join(hooks_dir, "post-commit")
    hook_content = """#!/usr/bin/env sh
# Auto-increment FWT version on every commit
python tools/version.py auto
"""
    with open(hook_path, "w", encoding="utf-8") as f:
        f.write(hook_content)

    print(f"Git post-commit hook successfully installed at: {hook_path}")


def main():
    parser = argparse.ArgumentParser(description="Field Worker Tracker Automated Versioning CLI")
    subparsers = parser.add_subparsers(dest="command")

    # Current
    subparsers.add_parser("current", help="Show current version")

    # Bump
    bump_parser = subparsers.add_parser("bump", help="Increment version manually (major, minor, or patch)")
    bump_parser.add_argument("level", choices=["major", "minor", "patch"], help="Level to increment")
    bump_parser.add_argument("--message", "-m", default="", help="Release note / reason")

    # Auto
    auto_parser = subparsers.add_parser("auto", help="Auto-increment based on git branch and commit")
    auto_parser.add_argument("--message", "-m", default="", help="Optional commit note")

    # Sync
    subparsers.add_parser("sync", help="Synchronize version across version.json, pyproject.toml, package.json, and docs")

    # Install Hook
    subparsers.add_parser("install-hook", help="Install git post-commit hook for automated versioning")

    args = parser.parse_args()

    if args.command == "current" or not args.command:
        v = load_version()
        print(f"v{v.get('version', '1.0.0')}")
    elif args.command == "bump":
        bump(args.level, args.message)
    elif args.command == "auto":
        auto_increment(args.message)
    elif args.command == "sync":
        v = load_version()
        sync_all_targets(v.get("version", "1.0.0"), "Synchronized targets")
        print(f"Synchronized all targets to v{v.get('version', '1.0.0')}")
    elif args.command == "install-hook":
        install_git_hook()


if __name__ == "__main__":
    main()
